import { useState } from "react";
import { ArrowRight, Cpu, KeyRound, LockKeyhole, Network, ShieldCheck } from "lucide-react";
import { api, setAdminKey } from "../lib/api";
import { Button, Input } from "./ui";

export function Login({ onAuthenticated }: { onAuthenticated: () => void }) {
  const [key, setKey] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  const submit = async () => {
    const candidate = key.trim();
    if (!candidate) {
      setError("Enter an administrator API key.");
      return;
    }
    setLoading(true);
    setError(null);
    setAdminKey(candidate);
    try {
      await api("/admin/api/auth/me");
      onAuthenticated();
    } catch (err) {
      setAdminKey("");
      setError(err instanceof Error ? err.message : "Authentication failed.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <main className="login-page">
      <section className="login-story">
        <div className="brand-lockup">
          <div className="brand-mark" aria-hidden="true">
            <span />
          </div>
          <div>
            <div className="brand-name">ModelSwitch</div>
            <div className="brand-sub">Local inference control plane</div>
          </div>
        </div>

        <div className="login-copy">
          <div className="eyebrow">One endpoint · every local model</div>
          <h1>
            Your models.
            <br />
            <em>One endpoint.</em>
          </h1>
          <p>
            A hardware-aware router in front of llama.cpp. It reads the task, checks
            live memory, and sends the request to the model that actually fits.
          </p>
        </div>

        <div className="flow-diagram" aria-label="Request flow">
          <div className="flow-node">
            <Network size={16} />
            <span>OpenAI client</span>
          </div>
          <div className="flow-rule" />
          <div className="flow-node is-core">
            <Cpu size={16} />
            <span>Task router</span>
          </div>
          <div className="flow-rule" />
          <div className="flow-node">
            <span className="flow-dot" />
            <span>llama.cpp</span>
          </div>
        </div>

        <div className="login-foot">
          <span>
            <ShieldCheck size={14} /> Loopback admin listener
          </span>
          <span>Inference never leaves this machine</span>
        </div>
      </section>

      <section className="login-panel">
        <div className="login-card">
          <div className="login-icon">
            <LockKeyhole size={20} />
          </div>
          <div className="eyebrow">Administrator access</div>
          <h2>Open the control room</h2>
          <p className="muted">
            Use an admin API key generated by <code>python -m app init</code>. Inference
            keys cannot open this interface.
          </p>

          <label className="field">
            <span className="field-label">Admin API key</span>
            <div className="input-with-icon">
              <KeyRound size={16} />
              <Input
                type="password"
                value={key}
                autoFocus
                autoComplete="off"
                spellCheck={false}
                placeholder="msk_…"
                onChange={(event) => setKey(event.target.value)}
                onKeyDown={(event) => event.key === "Enter" && void submit()}
                aria-invalid={Boolean(error)}
              />
            </div>
          </label>
          {error && (
            <div className="form-alert" role="alert">
              {error}
            </div>
          )}
          <Button variant="primary" size="md" loading={loading} onClick={() => void submit()} className="login-submit">
            Unlock dashboard <ArrowRight size={15} />
          </Button>
          <div className="login-note">
            The key is kept in this tab's <code>sessionStorage</code> and sent only as an
            <code> Authorization</code> header. It is never persisted by the dashboard.
          </div>
        </div>
        <p className="login-legal">
          ModelSwitch · open source · local-first
        </p>
      </section>
    </main>
  );
}
